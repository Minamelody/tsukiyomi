// 節月（1..12。正月節=立春から）。節入り日はその日から新しい節月（senjitsu.py と同一規約）。
function setsuMonth(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const dayKey = y * 10000 + m * 100 + d;
  let best = null;
  for (const yy of [y - 1, y, y + 1]) {
    const terms = SOLAR_TERMS[String(yy)];
    if (!terms) continue;
    for (let k = 1; k <= 12; k++) {
      const [mm, dd] = terms[k - 1].split('-').map(Number);
      const t = yy * 10000 + mm * 100 + dd;
      if (t <= dayKey && (best === null || t > best.t)) best = { t, k };
    }
  }
  return best ? best.k : 12;
}

