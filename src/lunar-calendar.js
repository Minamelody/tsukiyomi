// src/lunar-calendar.js — 選日（一粒万倍日・母倉日・天赦日・天恩日・三隣亡）の決定論JSポート。
// 無料鑑定ツール（line-fortune.js）の⑥運気セクションの「月内暦スキャン」に使う。
//
// senjitsu.py（ephem 使用・JAL SKYWARD+/benri.jp 等の外部暦と全件突合済み）と同じ判定を、
// ephem 無し・完全オフライン・決定論の純JSで再現する。ephem が必要なのは「節入り日」（太陽黄経）だけなので、
// ここだけ senjitsu._setsu_starts の結果を 1899〜2031年分プリ生成して SOLAR_TERMS に埋め込む。
// それ以外（日の干支・一粒万倍日・母倉日・天赦日・天恩日・三隣亡）は純粋なテーブル演算で、
// senjitsu.py の ICHIRYU/BOSO/TENSHA/TENON/SANRIN と完全に同一。

const JIKKAN = '甲乙丙丁戊己庚辛壬癸';
const JUNISHI = '子丑寅卯辰巳午未申酉戌亥';

// 日の干支の基準日（benri.jp 節月干支カレンダーで実測）。senjitsu.py と同じ基準。
const BASE_EPOCH_DAY = Date.UTC(2026, 7, 18) / 86400000; // 2026-08-18 = 甲子

function daysFromBase(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / 86400000) - BASE_EPOCH_DAY;
}

function dayKanshi(dateStr) {
  const d = daysFromBase(dateStr);
  const n = ((d % 60) + 60) % 60;
  return JIKKAN[n % 10] + JUNISHI[n % 12];
}

function dayShi(dateStr) {
  const d = daysFromBase(dateStr);
  return JUNISHI[((d % 12) + 12) % 12];
}
