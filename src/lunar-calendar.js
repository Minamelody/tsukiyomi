/** その年・その暦月に含まれる節入り（節月境界）の日。無ければ null（毎月ほぼ1回あり）。 */
function setsuDayInMonth(y, m) {
  const terms = SOLAR_TERMS[String(y)];
  if (!terms) return null;
  for (let k = 1; k <= 12; k++) {
    const [mm, dd] = terms[k - 1].split('-').map(Number);
    if (mm === m) return { k, dd };
  }
  return null;
}

