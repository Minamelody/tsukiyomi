function sunSign(m, d) {
  for (const [cm, cd, idx] of SUN_CUSP) {
    if (m === cm && d >= cd) return SIGNS[idx];
    if (m === cm % 12 + 1 && d < (SUN_CUSP.find(c => c[0] === m)?.[1] ?? 32)) { /* 次分岐で処理 */ }
  }
  // 月内で境界前なら前の星座
  const order = [[1,20,10,9],[2,19,11,10],[3,21,0,11],[4,20,1,0],[5,21,2,1],[6,22,3,2],
                 [7,23,4,3],[8,23,5,4],[9,23,6,5],[10,24,7,6],[11,23,8,7],[12,22,9,8]];
  const row = order.find(r => r[0] === m);
  return SIGNS[d >= row[1] ? row[2] : row[3]];
}

/**
 * 西洋占星術のホロスコープ（簡易）。
 * @param {string} birthday 'YYYY-MM-DD'
 */
function horoscope(birthday) {
  const [y, m, d] = birthday.split('-').map(Number);
  const sun = sunSign(m, d);

  // 月の平均運動: 約27.32日で12星座を巡る＝1星座あたり約2.28日
  const epoch = Date.UTC(2000, 0, 1) / 86400000;
  const days = Date.UTC(y, m - 1, d) / 86400000 - epoch;
  const moonIdx = Math.floor((((days / 27.321661) * 12) % 12 + 12)) % 12;
  const moon = SIGNS[moonIdx];

  // アセンダント: 出生時刻がないため生年月日からの推定
  const ascIdx = (SIGNS.indexOf(sun) + Math.floor(((days % 365.25) / 365.25) * 12)) % 12;
  const asc = SIGNS[(ascIdx + 12) % 12];

  return {
    sun: { ...sun, meaning: SUN_MEANING[sun.name] },
    moon: { ...moon, meaning: MOON_MEANING[moon.name] },
    ascendant: { ...asc, meaning: ASC_MEANING[asc.name], note: '正確な上昇宮の算出には出生時刻が必要です。ここでは生年月日からの推定値です' },
    dominantElement: (() => {
      const c = {};
      for (const s of [sun, moon, asc]) c[s.element] = (c[s.element] || 0) + 1;
      return Object.entries(c).sort((a, b) => b[1] - a[1])[0][0];
    })(),
  };
}

