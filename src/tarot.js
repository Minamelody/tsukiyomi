const POSITIONS = ['過去', '現在', '未来'];
const POSITION_MEANING = {
  過去: 'ここまでの流れと、今の状況を作った原因',
  現在: '今のあなたが置かれている状態',
  未来: 'このまま進んだ場合に向かう先',
};

function rng(seed) {
  let x = seed || 1;
  return () => { x ^= x << 13; x >>>= 0; x ^= x >> 17; x ^= x << 5; x >>>= 0; return x / 4294967296; };
}
function hash(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

/**
 * 3枚引き。
 * @param {string} seedStr 名前+生年月日+日付+悩み などの一意な文字列
 */
function draw3(seedStr) {
  const r = rng(hash(seedStr + '|tarot'));
  const deck = MAJOR.map((c, i) => ({ c, i }));
  // フィッシャー・イェーツで決定論的にシャッフル
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return POSITIONS.map((pos, idx) => {
    const { c } = deck[idx];
    const reversed = r() < 0.42;   // 逆位置の確率
    return {
      position: pos,
      positionMeaning: POSITION_MEANING[pos],
      card: c.name,
      number: c.n,
      reversed,
      orientation: reversed ? '逆位置' : '正位置',
      meaning: reversed ? c.rev : c.up,
    };
  });
}

