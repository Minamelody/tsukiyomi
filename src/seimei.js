/** 1文字の画数を返す。画数が確定できない文字は null を返す。
 *  推定はしない — 誤った画数で鑑定を出すより、その文字を扱えないと明示する方が安全。 */
function strokes(ch) {
  if (KANA[ch] != null) return KANA[ch];
  if (KANJI[ch] != null) return KANJI[ch];      // 姓名判断で慣用的な値を優先
  const u = kanjiStrokes(ch);
  if (u != null) return u;
  return null;
}

/** 画数を確定できない文字を列挙する（呼び出し側でユーザーに知らせるため） */
function unknownChars(str) {
  return [...(str || '')].filter(ch => strokes(ch) == null);
}

function luckOf(n) {
  // 81を超える場合は81で割った余り（伝統的な扱い）
  let k = n > 81 ? ((n - 1) % 81) + 1 : n;
  // 0画以下に吉凶は存在しない。以前は1へ丸めていたため
  // 「外格0画・大吉・独立と発展」という実在しない判定が出ていた（霊数補正で0は出なくなったが、
  // 丸め自体が誤りなので廃止する）。判定不能として返す。
  if (k < 1) return { n, luck: '—', meaning: '判定できません' };
  return { n, ...(LUCK[k] ? { luck: LUCK[k][0], meaning: LUCK[k][1] } : { luck: '吉', meaning: '安定' }) };
}

/**
 * 姓名判断。
 * @param {string} sei 姓
 * @param {string} mei 名
 */
function seimeiHandan(sei, mei) {
  const s = [...(sei || '').trim()].filter(c => c.trim());
  const m = [...(mei || '').trim()].filter(c => c.trim());
  if (!s.length || !m.length) return null;

  // 画数を確定できない文字が混ざったまま計算すると、五格すべてが誤った値になる。
  // 推定で埋めず、扱えない文字を明示して返す（呼び出し側でユーザーに知らせる）。
  const unknown = [...s, ...m].filter(c => strokes(c) == null);
  if (unknown.length) return { error: 'unknown_strokes', chars: unknown };

  const sN = s.map(strokes), mN = m.map(strokes);
  const sSum = sN.reduce((a, b) => a + b, 0);
  const mSum = mN.reduce((a, b) => a + b, 0);

  // 霊数補正（一字姓・一字名の伝統流派）:
  // 姓が1字なら天格（家系側）に、名が1字なら地格（本人側）に「霊数1」を足す。
  // 外格は補正後の天格＋地格−人格で出す（= 通常表記では総格−人格と同値になる）。
  // これをしないと一字姓・一字名の外格が 0画 になり、吉凶として誤表示される
  // （例: 林大 → 外格0「大吉」は流派として成立しない）。
  const tenkaku = sSum + (s.length === 1 ? 1 : 0);        // 天格: 姓の総和（一字姓は霊数+1）
  const jinkaku = sN[sN.length - 1] + mN[0];              // 人格: 姓の末字+名の頭字（性格の中心）
  const chikaku = mSum + (m.length === 1 ? 1 : 0);        // 地格: 名の総和（一字名は霊数+1）
  const soukaku = sSum + mSum;                            // 総格: 全体（生涯運・霊数補正なし）
  // 外格: 天格 + 地格 - 人格（対人・環境）
  const gaikaku = tenkaku + chikaku - jinkaku;

  // 霊数を補った側を返す。PDFの図版が「霊 1」の枠をどちらに描くかに使う。
  // これが無いと、図に8画・3画しか出ていないのに天格9・地格4と表示され、
  // 購入者が検算すると数字が合わない鑑定書になる。
  const reisu = (s.length === 1 ? ['姓'] : []).concat(m.length === 1 ? ['名'] : []);

  return {
    sei: sei, mei: mei,
    strokes: { sei: sN, mei: mN },
    reisu: reisu.length ? reisu : null,
    kaku: {
      天格: luckOf(tenkaku), 人格: luckOf(jinkaku), 地格: luckOf(chikaku),
      外格: luckOf(gaikaku), 総格: luckOf(soukaku),
    },
  };
}

